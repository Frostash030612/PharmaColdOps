import assert from "node:assert/strict";
import { createRegistration, saveRegistration, restoreRegistration, clearRegistration, sameRegistrationDraft } from "../frontend-vue/src/lib/registration.js";
const values = new Map();
const storage = { setItem: (k,v)=>values.set(k,v), getItem:k=>values.get(k)||null, removeItem:k=>values.delete(k) };
const data = { product_id:"vaccine_2_8", excursion_temp_c:20, duration_min:90, spec_override:{allowable_duration_min:30} };
const envelope = createRegistration(data, "new_inbound", "reg-stable", "2026-10-01T09:00:00Z");
data.duration_min = 91;
assert.equal(envelope.payload.duration_min,90);
assert.equal(sameRegistrationDraft({...data,duration_min:90},envelope),true);
assert.equal(sameRegistrationDraft(data,envelope),false);
assert.equal(envelope.payload.registration_id,"reg-stable");
assert.equal(saveRegistration(storage,"api-a",envelope),true);
assert.deepEqual(restoreRegistration(storage,"api-a"),envelope);
assert.equal(restoreRegistration(storage,"api-b"),null);
assert.equal(envelope.payload.started_at,"2026-10-01T09:00:00Z");
assert.equal(clearRegistration(storage,"api-a"),true);
assert.equal(restoreRegistration(storage,"api-a"),null);
assert.equal(saveRegistration({setItem(){throw new Error("quota");}},"a",envelope),false);
assert.notEqual(createRegistration({product_id:"x"}).payload.registration_id,createRegistration({product_id:"x"}).payload.registration_id);
console.log("Registration identity, immutable retry envelope and session recovery passed.");
